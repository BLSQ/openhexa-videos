// Turns raw voiceover clips into what the animation and the mixer read:
//   1. silence-trimmed 48 kHz mono WAVs, optionally sped up    vo/<lang>/trim/<id>.wav (re-made only when stale)
//   2. word timings with local Whisper (video.json "words": "whisper")  vo/<lang>/words/<id>.json
//   3. browser data (when video.json "gen" lists them)          gen/vo-<lang>.js, gen/script.js
//   node tools/prep.mjs <video> --lang en [--no-words] [--force]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ROOT, loadVideo, langOf, parseArgs, FFMPEG } from './lib.mjs';

const { opts, rest } = parseArgs(process.argv.slice(2));
const video = loadVideo(rest[0]);
const lang = langOf(video, process.argv);
const vo = path.join(video.dir, 'vo', lang);
const script = JSON.parse(fs.readFileSync(path.join(video.dir, 'script.json'), 'utf8'))[lang];
// Pitch-preserving speed-up, e.g. 1.06 to tighten a slower narrator.
const tempo = ((video.voices || {})[lang] || {}).tempo || 1;
for (const d of ['trim', 'words']) fs.mkdirSync(path.join(vo, d), { recursive: true });

const trimFilter = 'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.02,areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,areverse';
const data = {};
let trimmed = 0;
for (const line of script.lines) {
  const raw = ['mp3', 'aiff'].map((e) => path.join(vo, 'raw', `${line.id}.${e}`)).find((f) => fs.existsSync(f));
  if (!raw) throw new Error(`missing raw clip ${path.relative(ROOT, path.join(vo, 'raw', line.id))}.mp3: run tts first`);
  const wav = path.join(vo, 'trim', `${line.id}.wav`);
  if (opts.force || !fs.existsSync(wav) || fs.statSync(wav).mtimeMs < fs.statSync(raw).mtimeMs) {
    execFileSync(FFMPEG, ['-v', 'error', '-y', '-i', raw, '-af', trimFilter + (tempo !== 1 ? `,atempo=${tempo}` : ''), '-ar', '48000', '-ac', '1', wav]);
    trimmed++;
  }
  // WAV header: 16-bit mono at 48 kHz -> bytes / 96000 = seconds
  const dur = (fs.statSync(wav).size - 44) / 96000;
  data[line.id] = { dur: +dur.toFixed(3), placeholder: raw.endsWith('.aiff'), words: [] };
}
console.log(`${video.id}/${lang}: ${trimmed} clip(s) trimmed, ${script.lines.length - trimmed} up to date`);

if (video.words === 'whisper' && !opts['no-words']) {
  const venv = path.join(ROOT, '.venv', 'bin', 'python');
  execFileSync(fs.existsSync(venv) ? venv : 'python3', [path.join(ROOT, 'tools', 'audio', 'words.py'), '--video', video.dir, '--lang', lang], { stdio: 'inherit' });
}
for (const line of script.lines) {
  const wf = path.join(vo, 'words', `${line.id}.json`);
  if (fs.existsSync(wf)) {
    const w = JSON.parse(fs.readFileSync(wf, 'utf8'));
    if (Array.isArray(w)) data[line.id].words = w.map((x) => [x.w, +x.t.toFixed(3), +x.end.toFixed(3)]);
  }
}

if ((video.gen || []).length) {
  const gen = path.join(video.dir, 'gen');
  fs.mkdirSync(gen, { recursive: true });
  fs.writeFileSync(path.join(gen, `vo-${lang}.js`), `// Generated by tools/prep.mjs: trimmed clip durations and word timings (s) per narration line.\nwindow.VO_DATA = ${JSON.stringify(data, null, 1)};\n`);
  const all = JSON.parse(fs.readFileSync(path.join(video.dir, 'script.json'), 'utf8'));
  delete all._note;
  fs.writeFileSync(path.join(gen, 'script.js'), `// Generated from script.json by tools/prep.mjs.\nwindow.SCRIPT = ${JSON.stringify(all)};\n`);
  console.log(`wrote gen/vo-${lang}.js:`, Object.values(data).reduce((a, b) => a + b.dur, 0).toFixed(1) + 's of speech');
}
